import assert from "node:assert/strict";
import { createHash, randomUUID } from "node:crypto";
import { readFile, readlink, rm } from "node:fs/promises";
import { join } from "node:path";
import test, { type TestContext } from "node:test";
import { Client } from "pg";
import { service, startWorker, until } from "./observer-host.ts";

type Host = Awaited<ReturnType<typeof service>>;
type Card = { approvalId: string; invocationId: string; version: number };

async function account(host: Host, profile: string) {
  return (await host.post("/members", { engine: "codex", profile, requestId: randomUUID() })).memberId as string;
}
async function conversation(host: Host, memberId: string) {
  const requestId = randomUUID(), conversationId = randomUUID();
  const path = "/conversations/" + conversationId;
  await host.post("/conversations", { conversationId, memberId });
  const text = "record " + requestId;
  const submit = () => host.post(path + "/inputs", { requestId, text });
  const snapshot = async () => (await host.api(path)).json();
  const card = () => until(async (): Promise<Card | undefined> => (await snapshot()).state.pendingApprovals[0]);
  const answer = (c: Card, choice: "approve" | "deny") => host.post(path + "/human", {
    approvalId: c.approvalId, invocationId: c.invocationId, version: c.version, memberId, requestId, choice
  });
  return { requestId, conversationId, path, submit, snapshot, card, answer, text };
}

async function worker(t: TestContext, host: Host, profile: string) {
  const stop = startWorker(t, profile, "codex", true);
  await until(async () => (await host.db.query("SELECT 1 FROM birbcrew_ts.profiles WHERE engine='codex' AND name=$1", [profile])).rowCount || undefined);
  return stop;
}

async function nativeProcesses(workspace: string) {
  // Walk only subprocesses of this test. The native launcher changes cwd before exec.
  const visit = async (parent: number, ancestors: number[]): Promise<{ native: number; runner: number; supervisor: number } | undefined> => {
    const value = await readFile(`/proc/${parent}/task/${parent}/children`, "utf8").catch(() => "");
    for (const child of value.trim().split(/\s+/).filter(Boolean).map(Number)) {
      if (await readlink(`/proc/${child}/cwd`).catch(() => "") === workspace &&
        (await readlink(`/proc/${child}/exe`).catch(() => "")).endsWith("/codex")) {
        const supervisor = ancestors.at(-1);
        assert.ok(supervisor);
        assert.match(await readFile(`/proc/${parent}/cmdline`, "utf8"), /supervisor-runner\.ts/);
        assert.match(await readFile(`/proc/${supervisor}/cmdline`, "utf8"), /supervisor-host\.ts/);
        return { native: child, runner: parent, supervisor };
      }
      const found = await visit(child, [...ancestors, parent]);
      if (found) return found;
    }
  };
  return until(() => visit(process.pid, []));
}
async function state(pid: number) {
  return /^State:\s+(\w)/m.exec(await readFile(`/proc/${pid}/status`, "utf8").catch(() => ""))?.[1];
}

async function blockTransition(t: TestContext, host: Host, requestId: string, afterConfirmation: boolean) {
  const gate = new Client({ connectionString: process.env.BIRBCREW_TEST_DATABASE_URL });
  await gate.connect();
  const name = "crash_" + requestId.replaceAll("-", "");
  const table = afterConfirmation ? "turns" : "codex_live_calls";
  const phase = afterConfirmation ? "committed" : "delivered";
  // Request UUIDs are generated by this test. Other members keep their normal SQL path.
  await gate.query(`CREATE FUNCTION birbcrew_ts.${name}() RETURNS trigger LANGUAGE plpgsql AS $$
    BEGIN PERFORM pg_advisory_xact_lock(hashtextextended(NEW.request_id::text,42)); RETURN NEW; END $$`);
  await gate.query(`CREATE TRIGGER ${name} BEFORE UPDATE OF phase ON birbcrew_ts.${table}
    FOR EACH ROW WHEN (NEW.request_id='${requestId}'::uuid AND NEW.phase='${phase}')
    EXECUTE FUNCTION birbcrew_ts.${name}()`);
  const { rows: [holder] } = await gate.query("SELECT pg_backend_pid() AS pid,pg_advisory_lock(hashtextextended($1,42))", [requestId]);
  const release = () => gate.query("SELECT pg_advisory_unlock_all()");
  t.after(async () => {
    try {
      await release();
      await gate.query(`DROP TRIGGER ${name} ON birbcrew_ts.${table}`);
      await gate.query(`DROP FUNCTION birbcrew_ts.${name}()`);
    } finally { await gate.end(); }
  });
  const wait = () => until(async () => (await host.db.query(`SELECT 1 FROM pg_stat_activity
    WHERE wait_event='advisory' AND $1=ANY(pg_blocking_pids(pid))`, [holder.pid])).rowCount || undefined);
  return { release, wait };
}

async function observedNativeReceipts(requestId: string) {
  const file = process.env.BIRBCREW_PROOF_CODEX_REQUESTS;
  assert.ok(file, "Configure the local provider receipt log for native crash verification");
  const lines = await readFile(file, "utf8").catch((error: NodeJS.ErrnoException) => {
    if (error.code === "ENOENT") return "";
    throw error;
  });
  return lines.trim().split("\n").filter(Boolean).map(line => JSON.parse(line) as { callId: string; ids: string[] })
    .filter(row => row.callId === "call_" + requestId);
}

for (const boundary of ["before native receipt", "before host confirmation", "after host confirmation"] as const) {
  test("Codex retains the committed receipt on supervisor loss " + boundary, { timeout: 110_000 }, async t => {
    const host = await service(t);
    if (!process.env.BIRBCREW_PROOF_CODEX_REQUESTS) {
      const file = join(process.env.BIRBCREW_PROOF_STREAM_DIR!, "receipts-" + randomUUID() + ".jsonl");
      process.env.BIRBCREW_PROOF_CODEX_REQUESTS = file;
      t.after(async () => {
        delete process.env.BIRBCREW_PROOF_CODEX_REQUESTS;
        await rm(file, { force: true });
      });
    }
    const profile = "crash." + randomUUID();
    const stop = await worker(t, host, profile);
    const memberId = await account(host, profile);
    const op = await conversation(host, memberId);
    const first = host.attach(op.conversationId);
    await until(async () => first.events.some(e => e.type === "STATE_SNAPSHOT") || undefined);
    const confirmed = boundary === "after host confirmation";
    const gate = boundary === "before native receipt" ? undefined : await blockTransition(t, host, op.requestId, confirmed);
    await op.submit();
    const card = await op.card();
    const second = host.attach(op.conversationId);
    await until(async () => second.events.some(e => e.type === "STATE_SNAPSHOT") || undefined);
    const workspace = join(process.env.BIRBCREW_STATE_DIR!, "codex", createHash("sha256").update(host.ownerId).digest("hex"), memberId, op.conversationId, "workspace");
    const processes = await nativeProcesses(workspace);
    if (!gate) {
      process.kill(processes.native, "SIGSTOP");
      t.after(async () => {
        const cwd = await readlink(`/proc/${processes.native}/cwd`).catch(() => "");
        if (cwd === workspace && await state(processes.native) === "T") process.kill(processes.native, "SIGCONT");
      });
      await until(async () => await state(processes.native) === "T" || undefined);
    }
    assert.equal((await op.answer(card, "approve")).decision, "approve");
    const receipt = await until(async () => (await host.db.query<{ receipt_id: string }>(`SELECT receipt_id FROM birbcrew_ts.work_items
      WHERE conversation_id=$1 AND approval_id=$2`, [op.conversationId, card.approvalId])).rows[0]?.receipt_id);
    if (gate) {
      // On the first barrier the SDK emitted a completed MCP item. On the second the host has already confirmed it.
      await gate.wait();
      await until(async () => (await observedNativeReceipts(op.requestId)).some(r => r.ids.includes(receipt)) || undefined);
    } else {
      assert.equal(await state(processes.native), "T");
      assert.deepEqual(await observedNativeReceipts(op.requestId), []);
    }
    const phase = async () => (await host.db.query("SELECT phase FROM birbcrew_ts.codex_live_calls WHERE approval_id=$1", [card.approvalId])).rows[0].phase;
    assert.equal(await phase(), confirmed ? "delivered" : "dispatching");
    process.kill(processes.supervisor, "SIGKILL");
    await until(async () => [undefined, "Z"].includes(await state(processes.runner)) && [undefined, "Z"].includes(await state(processes.native)) || undefined);
    await gate?.release();
    await stop();
    await worker(t, host, profile);
    await Promise.all([first.done, second.done]);
    const terminal = await op.snapshot();
    const expected = {
      requestId: op.requestId, approvalId: card.approvalId, effect: "committed", receiptId: receipt,
      delivery: confirmed ? "confirmed" : "unknown"
    };
    assert.equal(terminal.state.phase, "failed");
    assert.deepEqual(terminal.state.liveOperations, [expected]);
    assert.deepEqual(terminal.state.interruptedCalls ?? [], confirmed ? [] : [expected]);
    assert.deepEqual(terminal.state.pendingApprovals, []);
    for (const reader of [first, second]) {
      assert.deepEqual(reader.agent.messages, terminal.messages);
      assert.equal(reader.events.at(-1)?.code, "MEMBER_FAILED");
      assert.equal(reader.events.filter(e => e.type === "TOOL_CALL_RESULT" && e.toolCallId === card.approvalId &&
        JSON.parse(String(e.content)).receiptId === receipt).length, 1);
    }
    const late = host.attach(op.conversationId);
    await late.done;
    assert.deepEqual(late.agent.state, terminal.state);
    assert.equal((await op.answer(card, "approve")).decision, "approve");
    assert.equal((await host.api(op.path + "/inputs", { requestId: op.requestId, text: op.text })).status, 409);
    const { rows: [stored] } = await host.db.query(`SELECT
      (SELECT count(*) FROM birbcrew_ts.native_launches WHERE conversation_id=$1) AS launches,
      (SELECT count(*) FROM birbcrew_ts.codex_live_calls WHERE conversation_id=$1) AS calls,
      (SELECT count(*) FROM birbcrew_ts.work_items WHERE conversation_id=$1) AS effects`, [op.conversationId]);
    assert.deepEqual(stored, { launches: "1", calls: "1", effects: "1" });
    assert.deepEqual((await observedNativeReceipts(op.requestId)).map(r => r.ids.includes(receipt)), gate ? [true] : []);
  });
}

test("Codex owner commands progress while both inference slots are occupied", { timeout: 100_000 }, async t => {
  const host = await service(t), profile = "slots." + randomUUID();
  await worker(t, host, profile);
  const ownerMember = await account(host, profile);
  const [approve, deny, cancel, last] = await Promise.all(Array.from({ length: 4 }, () => conversation(host, ownerMember)));
  await Promise.all([approve.submit(), deny.submit()]);
  const [firstCard, secondCard] = await Promise.all([approve.card(), deny.card()]);
  const inferenceState = async (op: typeof approve) => {
    const execution = host.temporal.workflow.getHandle(`birbcrew-ts/member/${ownerMember}/conversation/${op.conversationId}`);
    const description = await execution.describe();
    return description.raw.pendingActivities?.find(a => a.activityType?.name === "executeTurn");
  };
  async function occupied(a: typeof approve, b: typeof approve) {
    const { rows } = await host.db.query(`SELECT l.request_id FROM birbcrew_ts.codex_live_calls l
      JOIN birbcrew_ts.native_launches n USING(conversation_id,request_id,token)
      WHERE NOT n.stopped AND l.phase='waiting' AND l.request_id=ANY($1::uuid[])`, [[a.requestId, b.requestId]]);
    assert.deepEqual(new Set(rows.map(r => r.request_id)), new Set([a.requestId, b.requestId]));
    const activities = await Promise.all([inferenceState(a), inferenceState(b)]);
    assert.ok(activities.every(activity => activity?.lastStartedTime), "Both native activities have started");
  }
  await occupied(approve, deny);
  await cancel.submit();
  await until(async () => {
    const queued = await inferenceState(cancel);
    return queued && !queued.lastStartedTime ? true : undefined;
  });

  // This member uses another inference queue while the two protected callbacks remain parked.
  const other = await conversation(host, await account(host, "fixture.v1"));
  await host.post(other.path + "/inputs", { requestId: other.requestId, text: "remember available" });
  await until(async () => (await other.snapshot()).messages.at(-1)?.content === "stored available" || undefined);
  await occupied(approve, deny);

  assert.equal((await approve.answer(firstCard, "approve")).decision, "approve");
  const thirdCard = await cancel.card();
  await occupied(deny, cancel);
  await last.submit();
  assert.equal((await deny.answer(secondCard, "deny")).decision, "deny");
  const fourthCard = await last.card();
  await occupied(cancel, last);
  await host.post(cancel.path + "/cancel", { requestId: cancel.requestId });
  const interrupted = await until(async () => {
    const s = await cancel.snapshot();
    return s.state.phase === "failed" ? s : undefined;
  });
  assert.deepEqual(interrupted.state.interruptedCalls, [{ requestId: cancel.requestId, approvalId: thirdCard.approvalId, effect: "none", delivery: "unknown" }]);
  assert.equal((await last.answer(fourthCard, "deny")).decision, "deny");
  for (const op of [approve, deny, last]) {
    await until(async () => (await op.snapshot()).state.phase === "idle" || undefined);
  }
  const { rows } = await host.db.query("SELECT approval_id FROM birbcrew_ts.work_items WHERE conversation_id=ANY($1::uuid[])",
    [[approve, deny, cancel, last].map(op => op.conversationId)]);
  assert.deepEqual(rows, [{ approval_id: firstCard.approvalId }]);
});
